package dev.rodrigosambade.empleados;
import java.math.BigDecimal;
import java.sql.*;
import java.util.*;
public final class EmployeeRepository {
    public void init(Connection c)throws SQLException{
        try(var s=c.createStatement()){
            s.execute("create table if not exists empleados(id int generated by default as identity primary key,nombre varchar(120) not null,puesto varchar(120) not null,salario decimal(12,2) not null check(salario>=0))");
        }
    }
    public List<Employee> all(Connection c)throws SQLException{
        try(var ps=c.prepareStatement("select id,nombre,puesto,salario from empleados order by id");
        var rs=ps.executeQuery()){
            List<Employee>x=new ArrayList<>();
            while(rs.next())x.add(new Employee(rs.getInt(1),rs.getString(2),rs.getString(3),rs.getBigDecimal(4)));
            return List.copyOf(x);
        }
    }
    public Employee add(Connection c,String n,String job,BigDecimal salary)throws SQLException{
        if(n==null||n.isBlank()||job==null||job.isBlank()||salary==null||salary.signum()<0)throw new IllegalArgumentException("Datos de empleado inválidos");
        try(var ps=c.prepareStatement("insert into empleados(nombre,puesto,salario) values(?,?,?)",Statement.RETURN_GENERATED_KEYS)){
            ps.setString(1,n.trim());
            ps.setString(2,job.trim());
            ps.setBigDecimal(3,salary);
            ps.executeUpdate();
            try(var rs=ps.getGeneratedKeys()){
                rs.next();
                return new Employee(rs.getInt(1),n.trim(),job.trim(),salary);
            }
        }
    }
    public boolean delete(Connection c,int id)throws SQLException{
        try(var ps=c.prepareStatement("delete from empleados where id=?")){
            ps.setInt(1,id);
            return ps.executeUpdate()==1;
        }
    }
    public boolean updateSalary(Connection c,int id,BigDecimal salary)throws SQLException{
        if(salary==null||salary.signum()<0)throw new IllegalArgumentException("Salario negativo");
        try(var ps=c.prepareStatement("update empleados set salario=? where id=?")){
            ps.setBigDecimal(1,salary);
            ps.setInt(2,id);
            return ps.executeUpdate()==1;
        }
    }
}
