package dev.rodrigosambade.empleados;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

public final class EmployeeRepository {

    private static final String SELECT_ALL = """
            SELECT id, nombre, puesto, salario
              FROM empleados
             ORDER BY id
            """;

    public void init(Connection connection) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS empleados (
                        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nombre VARCHAR(120) NOT NULL,
                        puesto VARCHAR(120) NOT NULL,
                        salario DECIMAL(12,2) NOT NULL CHECK (salario >= 0)
                    )
                    """);
        }
    }

    public List<Employee> all(Connection connection) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(SELECT_ALL);
             ResultSet resultSet = statement.executeQuery()) {
            List<Employee> employees = new ArrayList<>();
            while (resultSet.next()) {
                employees.add(map(resultSet));
            }
            return List.copyOf(employees);
        }
    }

    public Employee add(
            Connection connection,
            String name,
            String job,
            BigDecimal salary) throws SQLException {
        String normalizedName = requireText(name, "Nombre");
        String normalizedJob = requireText(job, "Puesto");
        validateSalary(salary);

        String sql = "INSERT INTO empleados(nombre, puesto, salario) VALUES (?, ?, ?)";
        try (PreparedStatement statement = connection.prepareStatement(
                sql,
                Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, normalizedName);
            statement.setString(2, normalizedJob);
            statement.setBigDecimal(3, salary);
            statement.executeUpdate();

            try (ResultSet generatedKeys = statement.getGeneratedKeys()) {
                if (!generatedKeys.next()) {
                    throw new SQLException("No se obtuvo la clave del empleado");
                }
                return new Employee(
                        generatedKeys.getInt(1),
                        normalizedName,
                        normalizedJob,
                        salary);
            }
        }
    }

    public boolean delete(Connection connection, int id) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(
                "DELETE FROM empleados WHERE id = ?")) {
            statement.setInt(1, id);
            return statement.executeUpdate() == 1;
        }
    }

    public boolean updateSalary(
            Connection connection,
            int id,
            BigDecimal salary) throws SQLException {
        validateSalary(salary);

        try (PreparedStatement statement = connection.prepareStatement(
                "UPDATE empleados SET salario = ? WHERE id = ?")) {
            statement.setBigDecimal(1, salary);
            statement.setInt(2, id);
            return statement.executeUpdate() == 1;
        }
    }

    private static Employee map(ResultSet resultSet) throws SQLException {
        return new Employee(
                resultSet.getInt("id"),
                resultSet.getString("nombre"),
                resultSet.getString("puesto"),
                resultSet.getBigDecimal("salario"));
    }

    private static String requireText(String value, String field) {
        if (value == null || value.isBlank()) {
            throw new IllegalArgumentException(field + " obligatorio");
        }
        return value.trim();
    }

    private static void validateSalary(BigDecimal salary) {
        if (salary == null || salary.signum() < 0) {
            throw new IllegalArgumentException("Salario inválido");
        }
    }
}
